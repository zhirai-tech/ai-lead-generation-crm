/**
 * OWNER: t-worker. Simulation mailbox (protocol='simulation').
 *
 * Used for offline demos and tests: no network access, no real email is ever
 * sent. Outgoing messages are written to `<dataDir>/outbox/<workspace>/<account>`
 * as `.eml` files plus a JSON sidecar so the demo UI can show what "would" have
 * been sent. Inbound sync can fabricate exactly one clearly-labelled demo reply;
 * it must never look like a real customer message (from address uses the
 * reserved `.invalid` TLD, subject/body carry a DEMO marker and the raw headers
 * store `demo: true`).
 */
import fs from 'node:fs';
import path from 'node:path';
import { id } from '../core/ids.mjs';
import { nowIso } from '../core/time.mjs';

const DEMO_FROM = 'demo-inbound@simulation.zhirai.invalid';
const DEMO_TAG = '【演示数据 · DEMO】';

export function isSimulationAccount(account) {
  const protocol = account && (account.protocol || account.protocolName);
  return String(protocol || '').toLowerCase() === 'simulation';
}

function safeSegment(value, fallback = 'unknown') {
  const text = String(value || '').replace(/[^A-Za-z0-9._-]/g, '_').slice(0, 80);
  return text || fallback;
}

export function outboxDir({ dataDir, workspaceId, accountId }) {
  const root = path.join(dataDir || 'server/data', 'outbox');
  return path.join(root, safeSegment(workspaceId, 'workspace'), safeSegment(accountId, 'account'));
}

/**
 * "Send" a message into the simulation outbox.
 * @returns {{ok:true, simulation:true, messageId:string, outboxPath:string, writtenAt:string}}
 */
export function sendSimulated({ account = {}, message = {}, workspaceId = null, dataDir = null, logger = null } = {}) {
  const dir = outboxDir({ dataDir, workspaceId, accountId: account.id || account.accountId || 'sim' });
  fs.mkdirSync(dir, { recursive: true });
  const messageId = String(message.messageId || `<sim-${id('m').slice(-16)}@simulation.zhirai.invalid>`);
  const stamp = new Date().toISOString().replace(/[-:.]/g, '').replace('T', '-');
  const base = path.join(dir, `${stamp}-${safeSegment(messageId.replace(/[<>]/g, ''), 'message')}`);
  const emlPath = `${base}.eml`;
  const metaPath = `${base}.meta.json`;
  fs.writeFileSync(emlPath, String(message.raw || ''), 'utf8');
  fs.writeFileSync(
    metaPath,
    JSON.stringify(
      {
        demo: true,
        simulation: true,
        messageId,
        from: message.from || account.address || null,
        to: message.to || [],
        subject: message.subject || '',
        createdAt: nowIso(),
        note: 'simulation outbox: 该邮件未真实发送（演示模式）',
      },
      null,
      2,
    ),
    'utf8',
  );
  if (logger) logger.info('simulation mail written to outbox', { messageId, file: path.basename(emlPath) });
  return { ok: true, simulation: true, messageId, outboxPath: emlPath, writtenAt: nowIso() };
}

/**
 * Produce one clearly labelled demo inbound reply for a previously sent message.
 * Used by `email.sync` for simulation accounts only.
 * @returns {object} normalized inbound message
 */
export function simulateInboundReply({ outbound = null, account = {}, now = null } = {}) {
  const at = now || nowIso();
  const originalId = outbound?.message_id_header || null;
  const originalSubject = outbound?.subject || '（无主题）';
  const replyId = `<demo.${id('m').slice(-16).toLowerCase()}@simulation.zhirai.invalid>`;
  const body = [
    DEMO_TAG,
    '',
    '这是一封由模拟邮箱生成的演示回复，仅用于演示收件箱同步与意向识别流程。',
    '它不是真实客户邮件，请勿据此做出业务判断。',
    '',
    '（演示内容）您好，我们看到了您的邮件，希望了解更多产品资料与报价信息。',
    '',
    `模拟账号：${account.address || 'simulation@zhirai.invalid'}`,
    `生成时间：${at}`,
  ].join('\r\n');
  const headers = {
    'message-id': replyId,
    'in-reply-to': originalId || '',
    references: originalId || '',
    subject: `Re: ${originalSubject}`,
    from: `演示回复（非真实客户） <${DEMO_FROM}>`,
    to: account.address || 'simulation@zhirai.invalid',
    date: new Date(at).toUTCString(),
    'content-type': 'text/plain; charset=UTF-8',
  };
  return {
    uid: null,
    demo: true,
    messageId: replyId,
    inReplyTo: originalId,
    references: originalId ? [originalId] : [],
    subject: `Re: ${originalSubject}`,
    from: { name: '演示回复（非真实客户）', address: DEMO_FROM },
    to: [{ name: '', address: String(account.address || 'simulation@zhirai.invalid').toLowerCase() }],
    cc: [],
    date: new Date(at).toISOString(),
    text: body,
    html: '',
    headers,
    rawHeaders: { demo: true, simulation: true, note: 'demo inbound reply generated by simulation mailbox' },
  };
}

/** Build a raw RFC 822 representation for a demo message (for audits/tests). */
export function renderDemoMessage(message = {}) {
  const headerLines = Object.entries(message.headers || {}).map(([name, value]) => `${name}: ${value}`);
  return `${headerLines.join('\r\n')}\r\n\r\n${String(message.text || '').replace(/\r\n/g, '\n').replace(/\n/g, '\r\n')}`;
}

export default { isSimulationAccount, outboxDir, sendSimulated, simulateInboundReply, renderDemoMessage, DEMO_TAG };
